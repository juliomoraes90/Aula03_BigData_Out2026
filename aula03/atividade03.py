#Entrada
a = float(input('Insira o numero para A:'))
b = float(input('Insira o numero para B:'))

#Processamento
soma = a + b
sub = a - b
mult = a * b
div = a / b

#Saida
print(f'Resultado Soma: {soma}')
print(f'Resultado Subtração: {sub}')
print(f'Resultado Multiplicação: {mult}')
print(f'Resultado Divisão: {div}')